/// The rest of a cancel, from the `before_cancel` hooks on: `doc` is the stored document, or,
/// for a transition, as `before_transition` left it (the caller has refused a change to a locked
/// field). Writes docstatus 2 and, with `state`, the workflow state; a change to an
/// `allow_on_submit` field is validated and written too. There is no other validation: nothing
/// else changes.
pub(crate) async fn cancel_tail(
    client: &impl GenericClient,
    pipeline: &Pipeline<'_>,
    current: &StoredDocument,
    doc: Document,
    ctx: &HookContext<'_>,
    state: Option<&str>,
) -> Result<StoredDocument, DbError> {
    let Pipeline {
        registry,
        doctype,
        target,
    } = pipeline;
    run_hooks(registry, doctype, "before_cancel", |hooks| {
        hooks.before_cancel(ctx, &doc)
    })?;
    // Only a transition can have changed anything (an `allow_on_submit` field, see the caller).
    let null = Value::Null;
    let columns: BTreeMap<String, Value> = column_values(doctype, &doc, true)
        .into_iter()
        .filter(|(field, value)| current.values.get(field).unwrap_or(&null) != value)
        .collect();
    let mut errors = if columns.is_empty() {
        Vec::new()
    } else {
        validate(registry, doctype, &doc).err().unwrap_or_default()
    };
    let no_tables = BTreeMap::new();
    let (links, writes) = resolve(
        client,
        registry,
        target.caller,
        doctype,
        (&columns, &no_tables),
        Some(current),
        &mut errors,
    )
    .await?;
    if !errors.is_empty() {
        return Err(DbError::Validation(errors));
    }
    write_update(
        client,
        registry,
        doctype,
        target,
        (&with_state(columns, state), &links, &writes),
        Some(DocStatus::Cancelled),
    )
    .await
}

/// Amends a cancelled document: creates a **new draft** with a copy of its values and table
/// rows and returns it as stored. The cancelled document is not changed.
///
/// `doctype` must be submittable ([`DbError::NotSubmittable`]) and the document cancelled
/// ([`DbError::InvalidDocStatus`]). `expected_version` is the cancelled document's version, as
/// for [`delete`] (it keeps a stale caller from amending a document it has not read); the caller
/// becomes the `owner` and `modified_by` of the new draft. The caller needs the **amend** right
/// and must be able to read the cancelled document (an unreadable one is
/// [`DbError::NotFound`]); it does not need the create right.
///
/// **Name.** The new document is named `<root>-<n>`, not by the naming rule of the DocType (no
/// series number is taken). If the cancelled document is itself an amendment (it has
/// `amended_from`) and its name is `<root>-<k>`, the new name is `<root>-<k+1>`; otherwise it is
/// `<name>-1`. So `X` is amended as `X-1`, and `X-1` (once cancelled) as `X-2`. The new
/// document's `amended_from` is the cancelled document's name.
///
/// A cancelled document can be amended once: if the document with the new name already exists
/// and amends it, the call fails with [`DbError::AlreadyAmended`] (delete the amendment to amend
/// again). Concurrent amendments of the same document serialize on its row lock
/// (`FOR NO KEY UPDATE`).
///
/// **Edge case: stale `AlreadyAmended`.** `amended_from` has no foreign key and the check
/// looks only at the document with the new name. If a cancelled document in a chain is deleted
/// and re-created by amending its predecessor, a later amend can name an amendment of the
/// deleted document: `X`, `X-1`, `X-2`; delete `X-1`; amend `X` again (a new `X-1`), submit and
/// cancel it; amending it then fails with `AlreadyAmended { amended_by: "X-2" }`. Delete `X-2`
/// to amend again. There is no code change for this.
///
/// **Edge case: `unique` fields.** The copy repeats every value, and the cancelled original
/// still holds them, so a DocType with a `unique` field fails with [`DbError::UniqueViolation`]
/// unless a `before_insert` or `validate` hook checks `ctx.operation == Operation::Amend` and
/// changes the value (the original cannot be deleted or updated first: amend needs it, and a
/// cancelled document cannot be updated).
///
/// **Pipeline.** The cancelled document is read and locked, as for [`submit`]; then the
/// **insert** pipeline of [`insert`] runs on the copy: the `before_insert` and `validate` hooks
/// run with [`Operation::Amend`] (the document they see has the new name in `name`; a hook that
/// changes it is refused with [`DbError::Naming`]), the framework validates it, Links are
/// resolved (a target that was deleted since is a validation error), the new name is used and
/// the draft is written. A hook error is [`DbError::Hook`] and nothing is changed.
pub async fn amend(
    client: &mut impl GenericClient,
    registry: &Registry,
    doctype: &str,
    name: &str,
    expected_version: i64,
    caller: &Caller,
) -> Result<StoredDocument, DbError> {
    let doctype = document_doctype(registry, doctype)?;
    let tx = client.transaction().await?;
    let jobs = EnqueuedJobs::new();
    let stored = amend_in(
        &tx,
        registry,
        doctype,
        name,
        expected_version,
        caller,
        &jobs,
    )
    .await?;
    write_jobs(&tx, registry, &jobs, caller).await?;
    tx.commit().await?;
    Ok(stored)
}

async fn amend_in(
    client: &impl GenericClient,
    registry: &Registry,
    doctype: &DocType,
    name: &str,
    expected_version: i64,
    caller: &Caller,
    jobs: &EnqueuedJobs,
) -> Result<StoredDocument, DbError> {
    check_actor(caller.name())?;
    require_submittable(doctype, "amend")?;
    let grant = grant(doctype, caller, Right::Amend)?;
    let current = lock_current(
        client,
        registry,
        doctype,
        name,
        expected_version,
        "FOR NO KEY UPDATE",
        &grant,
    )
    .await?;
    require_status(doctype, &current, DocStatus::Cancelled, "amend")?;
    let new_name = amended_name(&current.name, current.amended_from.as_deref());
    let sql = format!(
        "SELECT \"amended_from\" FROM {} WHERE \"name\" = $1::text",
        quote_ident(&table_name(&doctype.name))
    );
    if let Some(row) = client.query_opt(&sql, &[&new_name]).await? {
        let amended_from: Option<String> = row.try_get(0)?;
        if amended_from.as_deref() == Some(current.name.as_str()) {
            return Err(DbError::AlreadyAmended {
                doctype: doctype.name.clone(),
                name: current.name,
                amended_by: new_name,
            });
        }
        // Some other document has the name: the insert below reports the unique violation.
    }
    let mut doc = as_document(&current);
    doc.name = Some(new_name.clone());
    let amend = AmendOf {
        from: current.name,
        name: new_name,
    };
    insert_in(client, registry, doctype, doc, caller, Some(&amend), jobs).await
}

/// The name of the amendment of a cancelled document, see [`amend`].
fn amended_name(name: &str, amended_from: Option<&str>) -> String {
    if amended_from.is_some()
        && let Some((root, number)) = name.rsplit_once('-')
        && !number.is_empty()
        && number.bytes().all(|b| b.is_ascii_digit())
        && let Ok(number) = number.parse::<u64>()
        && let Some(next) = number.checked_add(1)
    {
        return format!("{root}-{next}");
    }
    format!("{name}-1")
}

/// Deletes the document with this name, and its table rows, if its current `version` equals
/// `expected_version`. The caller's name is passed to the hooks (not stored, as there is no audit
/// yet, and not authenticated); an empty one is [`DbError::InvalidActor`], as for [`insert`] and
/// [`update`]. The caller needs the **delete** right and must be able to read the document, with
/// the permission checks of [`update`] (unreadable is [`DbError::NotFound`], a readable document
/// of somebody else under an `if_owner` delete right is [`DbError::PermissionDenied`]).
///
/// A different version is [`DbError::Conflict`] (nothing is deleted; under REPEATABLE READ or
/// SERIALIZABLE a stale writer gets SQLSTATE 40001 as [`DbError::Postgres`] instead, see
/// [`update`]); an unknown name is [`DbError::NotFound`]. The rows go with the document (the
/// `parent_id` foreign key is `ON DELETE CASCADE`). A document that other documents still link
/// to cannot be deleted: [`DbError::LinkedDocumentExists`] names the linking DocType (the
/// links are `ON DELETE RESTRICT`; for a link in a table row, the DocType that owns the row)
/// **only if the caller has read access to that DocType**; otherwise `referenced_by` is `None`
/// and the error says only that the document is still linked (ADR 0011). A
/// failed delete leaves a caller-owned transaction usable (the call ran in a savepoint).
///
/// **Pipeline.** In this order: the stored document and its rows are read with a row lock
/// (`FOR UPDATE`; an unknown name or another version is reported here, before any hook runs);
/// the registered `before_delete` hooks run with the stored document, rows included (a hook error
/// is [`DbError::Hook`] and nothing is deleted); the document is deleted.
///
/// A submitted document of a submittable DocType cannot be deleted
/// ([`DbError::InvalidDocStatus`], checked after the lock and before the hooks): only a draft or
/// a cancelled document can.
pub async fn delete(
    client: &mut impl GenericClient,
    registry: &Registry,
    doctype: &str,
    name: &str,
    expected_version: i64,
    caller: &Caller,
) -> Result<(), DbError> {
    let doctype = document_doctype(registry, doctype)?;
    let tx = client.transaction().await?;
    let jobs = EnqueuedJobs::new();
    delete_in(
        &tx,
        registry,
        doctype,
        name,
        expected_version,
        caller,
        &jobs,
    )
    .await?;
    write_jobs(&tx, registry, &jobs, caller).await?;
    tx.commit().await?;
    Ok(())
}

async fn delete_in(
    client: &impl GenericClient,
    registry: &Registry,
    doctype: &DocType,
    name: &str,
    expected_version: i64,
    caller: &Caller,
    jobs: &EnqueuedJobs,
) -> Result<(), DbError> {
    let grant = grant(doctype, caller, Right::Delete)?;
    // `FOR UPDATE` makes concurrent linkers (`FOR KEY SHARE`) wait, so `before_delete` hooks do
    // not run for a delete that a new link would then refuse.
    let current = lock_current(
        client,
        registry,
        doctype,
        name,
        expected_version,
        "FOR UPDATE",
        &grant,
    )
    .await?;
    if current.docstatus == Some(DocStatus::Submitted) {
        return Err(invalid_status(doctype, &current, "delete"));
    }
    let doc = as_document(&current);
    let ctx = HookContext::new(&doctype.name, caller.name(), Operation::Delete).with_jobs(jobs);
    run_hooks(registry, doctype, "before_delete", |hooks| {
        hooks.before_delete(&ctx, &doc)
    })?;
    let sql = format!(
        "DELETE FROM {} WHERE \"name\" = $1::text AND \"version\" = $2::bigint",
        quote_ident(&table_name(&doctype.name))
    );
    let deleted = client
        .execute(&sql, &[&name, &expected_version])
        .await
        .map_err(|e| match DbError::from_delete(e, &doctype.name, name) {
            DbError::LinkedDocumentExists {
                doctype,
                name,
                referenced_by: Some(by),
            } => DbError::LinkedDocumentExists {
                doctype,
                name,
                // Decision 9: name the referencing DocType only to a caller who may read it.
                referenced_by: Some(owning_doctype(registry, by))
                    .filter(|by| can_read_doctype(registry, by, caller)),
            },
            other => other,
        })?;
    if deleted == 0 {
        let target = Target {
            name,
            expected_version,
            caller,
            read_owner: grant.read_owner,
        };
        return Err(stale_or_missing(client, doctype, &target).await?);
    }
    // The history goes with the document: there is no audit trail yet, and a name can be reused.
    if doctype.workflow.is_some() {
        client
            .execute(
                "DELETE FROM fb_workflow_log WHERE doctype = $1::text AND name = $2::text",
                &[&doctype.name, &name],
            )
            .await?;
    }
    Ok(())
}

/// Writes the jobs the hooks of this operation enqueued, in the operation's transaction (the
/// outbox, ADR 0013): after every hook has run and before the commit, so a refused or rolled-back
/// operation leaves no job. An unknown job name or an oversize payload is [`DbError::Job`] and
/// fails the whole operation.
pub(crate) async fn write_jobs(
    client: &impl GenericClient,
    registry: &Registry,
    jobs: &EnqueuedJobs,
    caller: &Caller,
) -> Result<(), DbError> {
    crate::jobs::enqueue_collected(client, registry, jobs.take(), caller.name()).await
}

/// Calls `call` for every hook set registered for the DocType, in registration order, and stops
/// at the first error, which becomes [`DbError::Hook`] naming `hook`.
pub(crate) fn run_hooks(
    registry: &Registry,
    doctype: &DocType,
    hook: &'static str,
    mut call: impl FnMut(&dyn DocTypeHooks) -> Result<(), HookError>,
) -> Result<(), DbError> {
    for hooks in registry.hooks(&doctype.name) {
        call(hooks.as_ref()).map_err(|error| DbError::Hook {
            doctype: doctype.name.clone(),
            hook,
            message: error.message().to_owned(),
        })?;
    }
    Ok(())
}

/// The stored document as the [`Document`] hooks and validation work on.
pub(crate) fn as_document(stored: &StoredDocument) -> Document {
    Document {
        name: Some(stored.name.clone()),
        values: stored.values.clone(),
        tables: stored.tables.clone(),
    }
}

/// What a caller may do with one existing document for an operation, decided by the evaluator.
pub(crate) struct Grant<'a> {
    pub(crate) right: Right,
    /// With an `if_owner` *read*: the owner of the only documents the caller can see. `None`:
    /// every document. Applied in the SQL that finds the document.
    pub(crate) read_owner: Option<&'a str>,
    /// With an `if_owner` right: the owner of the only documents the right applies to.
    pub(crate) right_owner: Option<&'a str>,
}

/// The document an operation works on, for the errors of a write that matched no row.
pub(crate) struct Target<'a> {
    pub(crate) name: &'a str,
    pub(crate) expected_version: i64,
    pub(crate) caller: &'a Caller,
    pub(crate) read_owner: Option<&'a str>,
}

pub(crate) fn permission_denied(doctype: &DocType, right: Right) -> DbError {
    DbError::PermissionDenied {
        doctype: doctype.name.clone(),
        right,
    }
}

/// The caller's access for `right` on the DocType, or [`DbError::PermissionDenied`] when there
/// is none. The single call to the evaluator for everything but links.
pub(crate) fn access_to(
    doctype: &DocType,
    caller: &Caller,
    right: Right,
) -> Result<Access, DbError> {
    match evaluate(doctype, caller, right) {
        Access::Denied => Err(permission_denied(doctype, right)),
        access => Ok(access),
    }
}

/// The owner a statement must be limited to (`AND "owner" = $n`) for this access.
fn owner_scope(access: Access, caller: &Caller) -> Option<&str> {
    (access == Access::OwnerOnly).then(|| caller.name())
}

/// Checks the caller's name and its right to work on existing documents (`right` and read),
/// before any document is looked up. Fails with [`DbError::PermissionDenied`] when either is
/// denied at the DocType level, which says nothing about any document.
fn grant<'a>(doctype: &DocType, caller: &'a Caller, right: Right) -> Result<Grant<'a>, DbError> {
    check_actor(caller.name())?;
    let read =
        access_to(doctype, caller, Right::Read).map_err(|_| permission_denied(doctype, right))?;
    let needed = access_to(doctype, caller, right)?;
    Ok(Grant {
        right,
        read_owner: owner_scope(read, caller),
        right_owner: owner_scope(needed, caller),
    })
}

/// Like [`grant`] for an operation whose right is not known before the document is read (a
/// transition): only the caller's name and the read access are checked, the right is
/// [`Right::Read`] and is not limited to own documents.
pub(crate) fn read_grant<'a>(doctype: &DocType, caller: &'a Caller) -> Result<Grant<'a>, DbError> {
    check_actor(caller.name())?;
    let read = access_to(doctype, caller, Right::Read)?;
    Ok(Grant {
        right: Right::Read,
        read_owner: owner_scope(read, caller),
        right_owner: None,
    })
}

/// Submit and cancel are refused on a DocType with a workflow: its documents change state only
/// through a transition (ADR 0015). The first check of both, so it says nothing about a document.
fn require_no_workflow(doctype: &DocType, operation: &'static str) -> Result<(), DbError> {
    if doctype.workflow.is_some() {
        return Err(DbError::WorkflowRequired {
            doctype: doctype.name.clone(),
            operation,
        });
    }
    Ok(())
}

/// A draft in a state with `edit_roles` can be updated only by a caller who has one of them (on
/// top of the write right). The system context and an administrator pass, like everywhere. A
/// state without `edit_roles`, an unknown state and a document that is not a draft change nothing.
fn check_edit_roles(
    doctype: &DocType,
    current: &StoredDocument,
    caller: &Caller,
) -> Result<(), DbError> {
    let Some(state) = current
        .workflow_state
        .as_deref()
        .and_then(|name| doctype.workflow.as_ref()?.state(name))
        .filter(|state| !state.edit_roles.is_empty())
    else {
        return Ok(());
    };
    let allowed = match caller {
        Caller::User { roles, .. } => state.edit_roles.iter().any(|r| roles.contains(r)),
        Caller::System { .. } => true,
    };
    if allowed || caller.bypasses_permissions() {
        Ok(())
    } else {
        Err(DbError::EditDenied {
            doctype: doctype.name.clone(),
            state: state.name.clone(),
        })
    }
}

/// Whether the caller has any read access to the DocType (used to decide what an error may say).
fn can_read_doctype(registry: &Registry, doctype: &str, caller: &Caller) -> bool {
    registry
        .get(doctype)
        .is_some_and(|d| evaluate(d, caller, Right::Read) != Access::Denied)
}

/// Reads the document with this name and its rows, locking the document row with `lock` (a
/// fixed `FOR ...` clause) until the transaction ends. In this order: a name that does not exist
/// **or that the caller cannot read** is [`DbError::NotFound`] (the read scope is part of the
/// SQL, so an unreadable row is not even locked); a document the caller may not use `grant.right`
/// on is [`DbError::PermissionDenied`]; a version other than `expected_version` is
/// [`DbError::Conflict`]. Nothing else has been done at that point. Writers of the rows take this
/// lock first, so the rows read here cannot change under the caller.
pub(crate) async fn lock_current(
    client: &impl GenericClient,
    registry: &Registry,
    doctype: &DocType,
    name: &str,
    expected_version: i64,
    lock: &'static str,
    grant: &Grant<'_>,
) -> Result<StoredDocument, DbError> {
    let sql = format!("{} {lock}", get_sql(doctype, grant.read_owner.is_some()));
    let params: Vec<&(dyn ToSql + Sync)> = match &grant.read_owner {
        Some(owner) => vec![&name, owner],
        None => vec![&name],
    };
    let Some(row) = client.query_opt(&sql, &params).await? else {
        return Err(DbError::NotFound {
            doctype: doctype.name.clone(),
            name: name.to_owned(),
        });
    };
    let mut stored = decode_row(doctype, &row)?;
    if let Some(owner) = grant.right_owner
        && stored.owner != owner
    {
        return Err(permission_denied(doctype, grant.right));
    }
    if stored.version != expected_version {
        return Err(DbError::Conflict {
            doctype: doctype.name.clone(),
            name: name.to_owned(),
            expected: expected_version,
            current: stored.version,
        });
    }
    stored.tables = load_tables(client, registry, doctype, stored.id).await?;
    Ok(stored)
}

/// For a link from a child table row, the DocType that owns the row; any other name unchanged.
fn owning_doctype(registry: &Registry, referencing: String) -> String {
    registry
        .get(&referencing)
        .filter(|d| d.is_child)
        .and_then(|child| registry.parent_of(&child.name))
        .map_or(referencing, |(parent, _)| parent.name.clone())
}

/// The DocType that documents of `name` belong to: it must be in the registry and not a child.
pub(crate) fn document_doctype<'a>(
    registry: &'a Registry,
    name: &str,
) -> Result<&'a DocType, DbError> {
    match registry.get(name) {
        None => Err(DbError::UnknownDocType {
            name: name.to_owned(),
        }),
        Some(doctype) if doctype.is_child => Err(DbError::ChildDocType {
            doctype: name.to_owned(),
        }),
        Some(doctype) => Ok(doctype),
    }
}

/// The DocType a Link or Table field points at. A registry that passed `check_references` has it.
fn lookup_doctype<'a>(registry: &'a Registry, target: &str) -> Result<&'a DocType, DbError> {
    registry.get(target).ok_or_else(|| DbError::UnknownDocType {
        name: target.to_owned(),
    })
}

/// Why a write that matched no row (`name` and `version`) did nothing: the document does not
/// exist or is not readable by the caller ([`DbError::NotFound`]) or has another version
/// ([`DbError::Conflict`]). The row was locked and checked before, so this is only a safeguard;
/// it applies the read scope too, so even it cannot tell a hidden document from a missing one.
async fn stale_or_missing(
    client: &impl GenericClient,
    doctype: &DocType,
    target: &Target<'_>,
) -> Result<DbError, DbError> {
    let (name, expected_version) = (target.name, target.expected_version);
    let mut sql = format!(
        "SELECT \"version\" FROM {} WHERE \"name\" = $1::text",
        quote_ident(&table_name(&doctype.name))
    );
    let params: Vec<&(dyn ToSql + Sync)> = match &target.read_owner {
        Some(owner) => {
            sql.push_str(" AND \"owner\" = $2::text");
            vec![&name, owner]
        }
        None => vec![&name],
    };
    Ok(match client.query_opt(&sql, &params).await? {
        None => DbError::NotFound {
            doctype: doctype.name.clone(),
            name: name.to_owned(),
        },
        Some(row) => DbError::Conflict {
            doctype: doctype.name.clone(),
            name: name.to_owned(),
            expected: expected_version,
            current: row.try_get(0)?,
        },
    })
}

/// The rows to write for one Table field, with their Link values already resolved.
struct TableWrite<'a> {
    child: &'a DocType,
    rows: Vec<(&'a Row, BTreeMap<String, Uuid>)>,
}

/// Resolves the Links of the document's values and of every row. Returns the ids of the
/// document's Links and the rows to write; a Link name that does not exist is added to `errors`.
/// A target the caller cannot read counts as missing (decision 9, see [`resolve_links`]).
///
/// With `stored` (update and submit), a Link value that is already stored is kept: a document
/// Link that equals the stored one, and a row Link whose name is among the stored values of the
/// same field in the same table, is resolved with full access (the caller already sees that name
/// through `get`). Only new or changed Link values get the caller's read check.
async fn resolve<'a>(
    client: &impl GenericClient,
    registry: &'a Registry,
    caller: &Caller,
    doctype: &DocType,
    (values, tables): (&BTreeMap<String, Value>, &'a BTreeMap<String, Vec<Row>>),
    stored: Option<&StoredDocument>,
    errors: &mut Vec<ValidationError>,
) -> Result<(BTreeMap<String, Uuid>, Vec<TableWrite<'a>>), DbError> {
    // Fields that already have a problem are not looked up (their value may not even be
    // sendable to the database, for example text with NUL).
    let skip: BTreeSet<String> = errors
        .iter()
        .filter(|e| !matches!(e, ValidationError::InRow { .. }))
        .map(|e| e.field().to_owned())
        .collect();
    let kept_value = |field: &str, link: &str| {
        stored.is_some_and(|s| s.values.get(field) == Some(&Value::Text(link.to_owned())))
    };
    let (links, found) = resolve_links(
        client,
        (registry, caller),
        doctype,
        values,
        &skip,
        &kept_value,
    )
    .await?;
    errors.extend(found);

    let mut writes = Vec::new();
    for (name, rows) in tables {
        let Some(FieldType::Table { target }) = doctype.field(name).map(|f| &f.field_type) else {
            continue; // reported by validation
        };
        let child = lookup_doctype(registry, target)?;
        let mut resolved = Vec::with_capacity(rows.len());
        for (i, row) in rows.iter().enumerate() {
            let position = i + 1;
            let skip: BTreeSet<String> = errors
                .iter()
                .filter_map(|e| match e {
                    ValidationError::InRow { field, row, error }
                        if field == name && *row == position =>
                    {
                        Some(error.field().to_owned())
                    }
                    _ => None,
                })
                .collect();
            let kept_row = |field: &str, link: &str| {
                let link = Value::Text(link.to_owned());
                stored
                    .and_then(|s| s.tables.get(name))
                    .is_some_and(|rows| rows.iter().any(|r| r.get(field) == Some(&link)))
            };
            let (ids, found) =
                resolve_links(client, (registry, caller), child, row, &skip, &kept_row).await?;
            errors.extend(found.into_iter().map(|error| ValidationError::InRow {
                field: name.clone(),
                row: position,
                error: Box::new(error),
            }));
            resolved.push((row, ids));
        }
        writes.push(TableWrite {
            child,
            rows: resolved,
        });
    }
    Ok((links, writes))
}

/// Resolves the Link values in `values` (name -> target `id`), locking each target row against
/// deletion. A name that does not exist is returned as [`ValidationError::LinkNotFound`].
/// Fields in `skip` are not looked up. A value for which `kept(field, name)` is true is already
/// stored on the document: it is resolved with full access, without the caller's read check.
///
/// **Decision 9.** The lookup uses the caller's *read* access on the **target** DocType, so a
/// target the caller cannot read gives exactly the error of a missing one: with no read access to
/// the target DocType nothing is looked up at all; with an `if_owner` read the query has
/// `AND "owner" = $2` (bound, in SQL). The error is built in one place for both cases.
async fn resolve_links(
    client: &impl GenericClient,
    (registry, caller): (&Registry, &Caller),
    doctype: &DocType,
    values: &BTreeMap<String, Value>,
    skip: &BTreeSet<String>,
    kept: &(dyn Fn(&str, &str) -> bool + Sync),
) -> Result<(BTreeMap<String, Uuid>, Vec<ValidationError>), DbError> {
    let mut ids = BTreeMap::new();
    let mut errors = Vec::new();
    for (field, value) in values {
        let (Some(FieldType::Link { target }), Value::Text(target_name)) =
            (doctype.field(field).map(|f| &f.field_type), value)
        else {
            continue;
        };
        if skip.contains(field) {
            continue;
        }
        let target_type = lookup_doctype(registry, target)?;
        let mut sql = format!(
            "SELECT \"id\" FROM {} WHERE \"name\" = $1::text",
            quote_ident(&table_name(target))
        );
        let access = if kept(field, target_name) {
            Access::All
        } else {
            evaluate(target_type, caller, Right::Read)
        };
        let found = match access {
            Access::Denied => None,
            Access::All => {
                sql.push_str(" FOR KEY SHARE");
                client.query_opt(&sql, &[target_name]).await?
            }
            Access::OwnerOnly => {
                sql.push_str(" AND \"owner\" = $2::text FOR KEY SHARE");
                client
                    .query_opt(&sql, &[target_name, &caller.name()])
                    .await?
            }
        };
        match found {
            Some(row) => {
                ids.insert(field.clone(), row.try_get::<_, Uuid>(0)?);
            }
            None => errors.push(ValidationError::LinkNotFound {
                field: field.clone(),
                target: target.clone(),
                name: target_name.clone(),
            }),
        }
    }
    Ok((ids, errors))
}

/// Inserts the rows of every table, one `INSERT` per row, numbering them from 1.
async fn write_rows(
    client: &impl GenericClient,
    parent_id: Uuid,
    writes: &[TableWrite<'_>],
) -> Result<(), DbError> {
    let null = Value::Null;
    for write in writes {
        let sql = child_insert_sql(write.child);
        for ((row, links), idx) in write.rows.iter().zip(1_i32..) {
            let id = Uuid::now_v7();
            let mut params: Vec<&(dyn ToSql + Sync)> = vec![&id, &parent_id, &idx];
            let bound: Vec<SqlParam<'_>> = write
                .child
                .column_fields()
                .map(|field| {
                    sql_param(
                        &field.field_type,
                        links,
                        &field.name,
                        row.get(&field.name).unwrap_or(&null),
                    )
                })
                .collect();
            params.extend(bound.iter().map(|v| v as &(dyn ToSql + Sync)));
            client.execute(&sql, &params).await?;
        }
    }
    Ok(())
}

/// Reads the rows of every Table field of a document, in order.
async fn load_tables(
    client: &impl GenericClient,
    registry: &Registry,
    doctype: &DocType,
    parent_id: Uuid,
) -> Result<BTreeMap<String, Vec<Row>>, DbError> {
    let mut tables = BTreeMap::new();
    for (field, target) in doctype.table_fields() {
        let child = lookup_doctype(registry, target)?;
        let rows = client
            .query(&child_select_sql(child), &[&parent_id])
            .await?
            .iter()
            .map(|row| decode_fields(child, row, 0))
            .collect::<Result<Vec<_>, _>>()?;
        tables.insert(field.name.clone(), rows);
    }
    Ok(tables)
}

/// The bound parameter for one field: the resolved `id` for a Link, else the value itself.
fn sql_param<'a>(
    field_type: &FieldType,
    links: &BTreeMap<String, Uuid>,
    field: &str,
    value: &'a Value,
) -> SqlParam<'a> {
    match field_type {
        FieldType::Link { .. } => SqlParam::Link(links.get(field).copied()),
        _ => SqlParam::Value(SqlValue(value)),
    }
}

pub(crate) fn check_actor(actor: &str) -> Result<(), DbError> {
    if actor.is_empty() || actor.contains('\0') {
        return Err(DbError::InvalidActor);
    }
    Ok(())
}

/// The name for a new document. `doc` has passed validation. An amendment has the name its
/// rule gave it (a hook may not change it); the series takes the next number of its counter.
async fn new_name(
    client: &impl GenericClient,
    doctype: &DocType,
    doc: &Document,
    id: Uuid,
    amend: Option<&AmendOf>,
) -> Result<String, DbError> {
    if let Some(amend) = amend {
        if doc.name.as_deref() != Some(amend.name.as_str()) {
            return Err(DbError::Naming(format!(
                "an amended document is named `{}` and the name cannot be changed",
                amend.name
            )));
        }
        return Ok(amend.name.clone());
    }
    match &doctype.naming {
        Naming::Random => {
            if doc.name.is_some() {
                return Err(DbError::Naming(format!(
                    "DocType `{}` uses random naming: the name is generated and cannot be given",
                    doctype.name
                )));
            }
            Ok(id.hyphenated().to_string())
        }
        Naming::Field(field) => {
            let Some(Value::Text(name)) = doc.values.get(field) else {
                return Err(DbError::Naming(format!(
                    "field `{field}` must hold the document name"
                )));
            };
            if doc.name.as_ref().is_some_and(|given| given != name) {
                return Err(DbError::Naming(format!(
                    "the given name differs from the value of naming field `{field}`"
                )));
            }
            Ok(name.clone())
        }
        Naming::Series(pattern) => {
            if doc.name.is_some() {
                return Err(DbError::Naming(format!(
                    "DocType `{}` uses a naming series: the name is generated and cannot be given",
                    doctype.name
                )));
            }
            next_series_name(client, pattern).await
        }
    }
}

/// The counter statement: takes (creating it if needed) the row of the prefix, `$1`, and
/// increments it. The row lock lasts until the transaction ends.
const SERIES_SQL: &str = "INSERT INTO fb_series (prefix, current) VALUES ($1::text, 1) \
     ON CONFLICT (prefix) DO UPDATE SET current = fb_series.current + 1 RETURNING current";

/// The next name of a series: the prefix is rendered with the UTC date of the transaction, the
/// counter of that prefix is incremented in the caller's transaction and the number rendered.
async fn next_series_name(
    client: &impl GenericClient,
    pattern: &SeriesPattern,
) -> Result<String, DbError> {
    let date: Date = client
        .query_one("SELECT (now() AT TIME ZONE 'UTC')::date", &[])
        .await?
        .try_get(0)?;
    let prefix = pattern.prefix(date);
    let number: i64 = client.query_one(SERIES_SQL, &[&prefix]).await?.try_get(0)?;
    let number = u64::try_from(number).map_err(|_| {
        DbError::Naming(format!(
            "the counter of series prefix `{prefix}` holds {number}, which is not a valid number"
        ))
    })?;
    Ok(pattern.render(date, number))
}

/// `"id", "name", ..., "<field>", ...`: the columns of the table, in decode order.
fn column_list(doctype: &DocType) -> String {
    STANDARD_COLUMNS
        .iter()
        .copied()
        .chain(doctype.column_fields().map(|f| f.name.as_str()))
        .map(quote_ident)
        .collect::<Vec<_>>()
        .join(", ")
}

/// What every statement returns for the fields, in decode order: the column, except that a Link
/// column is replaced by the target document's `name` (a scalar subquery on the target's `id`,
/// aliased to the field name; the outer column is qualified with the table name so a self-link
/// resolves).
fn field_items(doctype: &DocType) -> Vec<String> {
    let table = quote_ident(&table_name(&doctype.name));
    doctype
        .column_fields()
        .map(|field| {
            let column = quote_ident(&field.name);
            match &field.field_type {
                FieldType::Link { target } => format!(
                    "(SELECT t.\"name\" FROM {} t WHERE t.\"id\" = {table}.{column}) AS {column}",
                    quote_ident(&table_name(target))
                ),
                _ => column,
            }
        })
        .collect()
}

/// The columns after the standard ones that only a submittable DocType's table has.
pub(crate) fn status_columns(doctype: &DocType) -> &'static [&'static str] {
    if doctype.submittable {
        &["docstatus", "amended_from"]
    } else {
        &[]
    }
}

/// The column after the [`status_columns`] that only the table of a DocType with a workflow has.
fn workflow_columns(doctype: &DocType) -> &'static [&'static str] {
    if doctype.workflow.is_some() {
        &[WORKFLOW_COLUMN]
    } else {
        &[]
    }
}

/// What every statement on a document table returns, in decode order: the standard columns, the
/// [`status_columns`], the [`workflow_columns`], then [`field_items`].
pub(crate) fn select_list(doctype: &DocType) -> String {
    let mut items: Vec<String> = STANDARD_COLUMNS
        .iter()
        .chain(status_columns(doctype))
        .chain(workflow_columns(doctype))
        .copied()
        .map(quote_ident)
        .collect();
    items.extend(field_items(doctype));
    items.join(", ")
}

/// The statement for one document by name (`$1`); with `owner_only` it is limited to the
/// caller's own documents (`$2`), which is how an `if_owner` read is applied.
fn get_sql(doctype: &DocType, owner_only: bool) -> String {
    format!(
        "SELECT {} FROM {} WHERE \"name\" = $1::text{}",
        select_list(doctype),
        quote_ident(&table_name(&doctype.name)),
        if owner_only {
            " AND \"owner\" = $2::text"
        } else {
            ""
        }
    )
}

/// `$1::<type>, $2::<type>, ...` for the column fields, numbered from `first`.
fn field_placeholders(doctype: &DocType, first: usize) -> Vec<String> {
    doctype
        .column_fields()
        .enumerate()
        .map(|(i, field)| format!("${}::{}", first + i, cast_type(&field.field_type)))
        .collect()
}

/// Placeholders `$1` (id), `$2` (name) and `$3` (actor, used twice), then one per column field,
/// then, for an amendment, `amended_from`, then, for a DocType with a workflow, the initial state.
/// `docstatus` is not written: its default (0) is a draft.
fn insert_sql(doctype: &DocType, amended: bool) -> String {
    let mut values = vec![
        "$1::uuid".to_owned(),
        "$2::text".to_owned(),
        "$3::text".to_owned(),
        "now()".to_owned(),
        "now()".to_owned(),
        "$3::text".to_owned(),
        "1".to_owned(),
    ];
    values.extend(field_placeholders(doctype, 4));
    let mut columns = column_list(doctype);
    if amended {
        columns.push_str(", ");
        columns.push_str(&quote_ident("amended_from"));
        values.push(format!("${}::text", 4 + doctype.column_fields().count()));
    }
    if doctype.workflow.is_some() {
        let n = 4 + doctype.column_fields().count() + usize::from(amended);
        columns.push_str(", ");
        columns.push_str(&quote_ident(WORKFLOW_COLUMN));
        values.push(format!("${n}::text"));
    }
    format!(
        "INSERT INTO {} ({columns}) VALUES ({}) RETURNING {}",
        quote_ident(&table_name(&doctype.name)),
        values.join(", "),
        select_list(doctype)
    )
}

/// Placeholders `$1` (row id), `$2` (parent id) and `$3` (idx), then one per field of the child.
fn child_insert_sql(child: &DocType) -> String {
    let columns: Vec<String> = ["id", "parent_id", "idx"]
        .into_iter()
        .chain(child.column_fields().map(|f| f.name.as_str()))
        .map(quote_ident)
        .collect();
    let mut values = vec![
        "$1::uuid".to_owned(),
        "$2::uuid".to_owned(),
        "$3::integer".to_owned(),
    ];
    values.extend(field_placeholders(child, 4));
    format!(
        "INSERT INTO {} ({}) VALUES ({})",
        quote_ident(&table_name(&child.name)),
        columns.join(", "),
        values.join(", ")
    )
}

/// The rows of a parent (`$1` = its id) in order, as [`field_items`].
fn child_select_sql(child: &DocType) -> String {
    format!(
        "SELECT {} FROM {} WHERE \"parent_id\" = $1::uuid ORDER BY \"idx\"",
        field_items(child).join(", "),
        quote_ident(&table_name(&child.name))
    )
}

/// Placeholders `$1..$n` for the changes (in key order), `$n+1` actor, `$n+2` name,
/// `$n+3` expected version. With `status` the new docstatus is set too (a constant of the
/// enum, not a value from outside).
/// `changes` has passed validation, so every key is a field of the DocType (the `text` fallback
/// cast is unreachable; an unknown column would be rejected by the database, never interpolated).
fn update_sql(
    doctype: &DocType,
    changes: &BTreeMap<String, Value>,
    status: Option<DocStatus>,
) -> String {
    let mut sets: Vec<String> = Vec::with_capacity(changes.len() + 3);
    for (i, name) in changes.keys().enumerate() {
        let cast = doctype
            .field(name)
            .map_or("text", |f| cast_type(&f.field_type));
        sets.push(format!("{} = ${}::{cast}", quote_ident(name), i + 1));
    }
    let n = changes.len();
    sets.push("\"modified_at\" = now()".to_owned());
    sets.push(format!("\"modified_by\" = ${}::text", n + 1));
    sets.push("\"version\" = \"version\" + 1".to_owned());
    if let Some(status) = status {
        sets.push(format!("\"docstatus\" = {}", status.as_i16()));
    }
    format!(
        "UPDATE {} SET {} WHERE \"name\" = ${}::text AND \"version\" = ${}::bigint RETURNING {}",
        quote_ident(&table_name(&doctype.name)),
        sets.join(", "),
        n + 2,
        n + 3,
        select_list(doctype)
    )
}

/// Decodes the column fields of `doctype` from `row`, starting at column `offset`.
fn decode_fields(
    doctype: &DocType,
    row: &PgRow,
    offset: usize,
) -> Result<BTreeMap<String, Value>, DbError> {
    let mut values = BTreeMap::new();
    for (i, field) in doctype.column_fields().enumerate() {
        let value = decode(row, offset + i, &field.field_type)
            .map_err(|e| DbError::decode(&doctype.name, &field.name, &e))?;
        values.insert(field.name.clone(), value);
    }
    Ok(values)
}

/// Decodes a row of [`select_list`]. `tables` is left empty for the caller to fill.
pub(crate) fn decode_row(doctype: &DocType, row: &PgRow) -> Result<StoredDocument, DbError> {
    let (docstatus, amended_from) = if doctype.submittable {
        let raw: i16 = row.try_get(STANDARD_COLUMNS.len())?;
        let status = DocStatus::from_i16(raw).ok_or_else(|| DbError::Decode {
            doctype: doctype.name.clone(),
            field: "docstatus".to_owned(),
            message: format!("{raw} is not a docstatus (0, 1 or 2)"),
        })?;
        (Some(status), row.try_get(STANDARD_COLUMNS.len() + 1)?)
    } else {
        (None, None)
    };
    let status_len = status_columns(doctype).len();
    let workflow_state = if doctype.workflow.is_some() {
        row.try_get(STANDARD_COLUMNS.len() + status_len)?
    } else {
        None
    };
    Ok(StoredDocument {
        id: row.try_get(0)?,
        name: row.try_get(1)?,
        owner: row.try_get(2)?,
        created_at: row.try_get(3)?,
        modified_at: row.try_get(4)?,
        modified_by: row.try_get(5)?,
        version: row.try_get(6)?,
        docstatus,
        amended_from,
        workflow_state,
        values: decode_fields(
            doctype,
            row,
            STANDARD_COLUMNS.len() + status_len + workflow_columns(doctype).len(),
        )?,
        tables: BTreeMap::new(),
    })
}

