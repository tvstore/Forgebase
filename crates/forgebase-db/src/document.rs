//! Document persistence: insert, get, update and delete of one document, with its child table
//! rows, in the tables of its DocType.
//!
//! Every function takes a mutable [`GenericClient`] (a pooled connection or a caller-owned
//! [`Transaction`](tokio_postgres::Transaction)) and the [`Registry`], and runs all of its
//! statements inside `client.transaction()`: a real transaction on a pooled connection, a
//! savepoint when the caller already has a transaction. A document and its rows are therefore
//! written atomically whichever client is passed, and a failed call leaves a caller's transaction
//! usable. SQL is built only from validated, quoted identifiers and numeric placeholders with
//! explicit casts; values are always bound parameters.
//!
//! Link fields hold the target's `id` in the database; this module resolves the target `name` to
//! the `id` on the way in and back to the `name` on the way out (see [`insert`]). Table fields
//! are rows of a child DocType's table, see [`insert`] and [`update`].
//!
//! The app's lifecycle hooks ([`forgebase_core::hooks::DocTypeHooks`], registered in the
//! [`Registry`]) run inside the same transaction at fixed points: the order of every operation
//! is listed in the documentation of [`insert`], [`update`] and [`delete`]. A hook error rolls
//! everything back ([`DbError::Hook`]). Hooks cannot reach the database. They may enqueue
//! background jobs: after the hooks and before the commit, the jobs they asked for are inserted
//! in the same transaction (the outbox, [`crate::jobs`], ADR 0013), so a job exists if and only
//! if the operation committed. An unknown job name or an oversize payload is [`DbError::Job`]
//! and fails the operation.
//!
//! DocTypes with `submittable = true` also have [`submit`], [`cancel`] and [`amend`], and their
//! documents carry a [`DocStatus`]: see those functions for the rules. A DocType with a
//! `[workflow]` (M8.1, ADR 0015) changes state only through [`crate::transition`], which continues
//! in the update, submit or cancel pipeline of this module; [`submit`] and [`cancel`] refuse it
//! ([`DbError::WorkflowRequired`]).
//!
//! # Permissions (M3.2, ADR 0011)
//!
//! Every operation takes the [`Caller`] and enforces the DocType's `[[permissions]]` with the one
//! evaluator, [`forgebase_core::permission::evaluate`]; this module never compares roles itself.
//! The [`Access`] it returns is applied as follows:
//!
//! - **Read access is applied in SQL**, never by fetching and filtering: for
//!   [`Access::OwnerOnly`] every statement that finds a document has `AND "owner" = $n` (bound).
//!   A document the caller cannot read is therefore *not found*: [`get`] returns `None`, and
//!   every other operation fails with [`DbError::NotFound`], **before** the version is compared
//!   (a stale version on an unreadable document is `NotFound`, never `Conflict`).
//! - A right the caller does not have on the DocType at all ([`Access::Denied`], which does not
//!   depend on any document) is [`DbError::PermissionDenied`], before anything is looked up. So is
//!   a right limited to own documents (`if_owner`) on a readable document of somebody else. Both
//!   say nothing about the data.
//! - A Link name is resolved with the caller's *read* access on the **target** DocType: a target
//!   the caller cannot read is reported exactly like a missing one.
//! - Child rows follow the parent document; they are never addressed alone.
//!
//! The [`Caller::System`] context and the `Administrator` role bypass the rules.

