//! Document persistence: insert, get, update and delete of one document in a DocType table.
//!
//! Every function takes a [`GenericClient`], so it runs on a pooled connection (each call is
//! then its own implicit transaction) or inside a [`Transaction`](tokio_postgres::Transaction)
//! that the caller owns and commits. SQL is built only from validated, quoted identifiers and
//! numeric placeholders with explicit casts; values are always bound parameters.

use std::collections::BTreeMap;

use forgebase_core::document::{Document, validate, validate_update};
use forgebase_core::ident::table_name;
use forgebase_core::meta::{DocType, Naming};
use forgebase_core::value::Value;
use time::OffsetDateTime;
use tokio_postgres::GenericClient;
use tokio_postgres::Row;
use tokio_postgres::types::ToSql;
use uuid::Uuid;

use crate::error::DbError;
use crate::ident::quote_ident;
use crate::value::{SqlValue, cast_type, decode};

/// The standard columns, in the order they are selected (see `plan.rs`: the DDL has the same).
const STANDARD_COLUMNS: [&str; 7] = [
    "id",
    "name",
    "owner",
    "created_at",
    "modified_at",
    "modified_by",
    "version",
];

/// A document as stored: the standard columns and the field values.
#[derive(Debug, Clone, PartialEq)]
pub struct StoredDocument {
    /// Surrogate key (UUID v7, generated by the application).
    pub id: Uuid,
    /// The human-facing unique name.
    pub name: String,
    /// The actor that created the document.
    pub owner: String,
    /// Creation time (database `now()`, that is the transaction start time).
    pub created_at: OffsetDateTime,
    /// Time of the last change (database `now()`).
    pub modified_at: OffsetDateTime,
    /// The actor that made the last change.
    pub modified_by: String,
    /// Starts at 1 and is incremented by every update.
    pub version: i64,
    /// One entry per field of the DocType, in field-name order; [`Value::Null`] when absent.
    pub values: BTreeMap<String, Value>,
}

/// Inserts a document and returns it as stored.
///
/// `doc` is validated first ([`forgebase_core::document::validate`], all problems collected in
/// [`DbError::Validation`]). The name follows the DocType's naming rule: with
/// [`Naming::Random`] it is the new UUID v7 and `doc.name` must be `None`; with
/// [`Naming::Field`] it is the value of that field and `doc.name` must be `None` or equal to it
/// ([`DbError::Naming`]). `actor` (a non-empty string without NUL, [`DbError::InvalidActor`]) is
/// recorded as `owner` and `modified_by`; it is not authenticated here. `created_at` and
/// `modified_at` come from the database's `now()`, and `version` is 1. A duplicate value in a
/// `unique` field or a duplicate name is [`DbError::UniqueViolation`].
pub async fn insert(
    client: &impl GenericClient,
    doctype: &DocType,
    doc: Document,
    actor: &str,
) -> Result<StoredDocument, DbError> {
    check_actor(actor)?;
    validate(doctype, &doc).map_err(DbError::Validation)?;
    let id = Uuid::now_v7();
    let name = new_name(doctype, &doc, id)?;

    let sql = insert_sql(doctype);
    let (id_value, name_value, actor_value) = (id, name, actor);
    let mut params: Vec<&(dyn ToSql + Sync)> = vec![&id_value, &name_value, &actor_value];
    let null = Value::Null;
    let bound: Vec<SqlValue<'_>> = doctype
        .fields
        .iter()
        .map(|field| SqlValue(doc.values.get(&field.name).unwrap_or(&null)))
        .collect();
    params.extend(bound.iter().map(|v| v as &(dyn ToSql + Sync)));

    let row = client
        .query_one(&sql, &params)
        .await
        .map_err(DbError::from_write)?;
    decode_row(doctype, &row)
}

/// Returns the document with this name, or `None`.
pub async fn get(
    client: &impl GenericClient,
    doctype: &DocType,
    name: &str,
) -> Result<Option<StoredDocument>, DbError> {
    let row = client.query_opt(&get_sql(doctype), &[&name]).await?;
    row.map(|row| decode_row(doctype, &row)).transpose()
}

/// Changes the given fields of an existing document and returns it as stored.
///
/// Only the fields in `changes` are written (a [`Value::Null`] clears one). `changes` is checked
/// with [`forgebase_core::document::validate_update`]. Changing the naming field is rejected
/// ([`DbError::Naming`]): renames are not supported yet. Empty `changes` are
/// [`DbError::NoChanges`]. `modified_at` is set to the database's `now()`, `modified_by` to
/// `actor`, and `version` is incremented; `created_at` and `owner` stay. There is no
/// optimistic concurrency check yet: the last writer wins. An unknown name is
/// [`DbError::NotFound`].
pub async fn update(
    client: &impl GenericClient,
    doctype: &DocType,
    name: &str,
    changes: &BTreeMap<String, Value>,
    actor: &str,
) -> Result<StoredDocument, DbError> {
    check_actor(actor)?;
    if changes.is_empty() {
        return Err(DbError::NoChanges);
    }
    validate_update(doctype, changes).map_err(DbError::Validation)?;
    if let Naming::Field(field) = &doctype.naming
        && changes.contains_key(field)
    {
        return Err(DbError::Naming(format!(
            "field `{field}` gives the document its name and cannot be changed (renames are not supported yet)"
        )));
    }

    let sql = update_sql(doctype, changes);
    let bound: Vec<SqlValue<'_>> = changes.values().map(SqlValue).collect();
    let mut params: Vec<&(dyn ToSql + Sync)> =
        bound.iter().map(|v| v as &(dyn ToSql + Sync)).collect();
    params.push(&actor);
    params.push(&name);

    let row = client
        .query_opt(&sql, &params)
        .await
        .map_err(DbError::from_write)?;
    match row {
        Some(row) => decode_row(doctype, &row),
        None => Err(not_found(doctype, name)),
    }
}

/// Deletes the document with this name. An unknown name is [`DbError::NotFound`].
pub async fn delete(
    client: &impl GenericClient,
    doctype: &DocType,
    name: &str,
) -> Result<(), DbError> {
    let sql = format!(
        "DELETE FROM {} WHERE \"name\" = $1::text",
        quote_ident(&table_name(&doctype.name))
    );
    if client.execute(&sql, &[&name]).await? == 0 {
        return Err(not_found(doctype, name));
    }
    Ok(())
}

fn not_found(doctype: &DocType, name: &str) -> DbError {
    DbError::NotFound {
        doctype: doctype.name.clone(),
        name: name.to_owned(),
    }
}

fn check_actor(actor: &str) -> Result<(), DbError> {
    if actor.is_empty() || actor.contains('\0') {
        return Err(DbError::InvalidActor);
    }
    Ok(())
}

/// The name for a new document. `doc` has passed validation.
fn new_name(doctype: &DocType, doc: &Document, id: Uuid) -> Result<String, DbError> {
    match &doctype.naming {
        Naming::Random => {
            if doc.name.is_some() {
                return Err(DbError::Naming(format!(
                    "DocType `{}` uses random naming: the name is generated and cannot be given",
                    doctype.name
                )));
            }
            Ok(id.hyphenated().to_string())
        }
        Naming::Field(field) => {
            let Some(Value::Text(name)) = doc.values.get(field) else {
                return Err(DbError::Naming(format!(
                    "field `{field}` must hold the document name"
                )));
            };
            if doc.name.as_ref().is_some_and(|given| given != name) {
                return Err(DbError::Naming(format!(
                    "the given name differs from the value of naming field `{field}`"
                )));
            }
            Ok(name.clone())
        }
    }
}

/// `"id", "name", ..., "<field>", ...`: the columns every statement returns, in decode order.
fn column_list(doctype: &DocType) -> String {
    STANDARD_COLUMNS
        .iter()
        .copied()
        .chain(doctype.fields.iter().map(|f| f.name.as_str()))
        .map(quote_ident)
        .collect::<Vec<_>>()
        .join(", ")
}

fn get_sql(doctype: &DocType) -> String {
    format!(
        "SELECT {} FROM {} WHERE \"name\" = $1::text",
        column_list(doctype),
        quote_ident(&table_name(&doctype.name))
    )
}

/// Placeholders `$1` (id), `$2` (name) and `$3` (actor, used twice), then one per field.
fn insert_sql(doctype: &DocType) -> String {
    let mut values = vec![
        "$1::uuid".to_owned(),
        "$2::text".to_owned(),
        "$3::text".to_owned(),
        "now()".to_owned(),
        "now()".to_owned(),
        "$3::text".to_owned(),
        "1".to_owned(),
    ];
    for (i, field) in doctype.fields.iter().enumerate() {
        values.push(format!("${}::{}", i + 4, cast_type(&field.field_type)));
    }
    format!(
        "INSERT INTO {} ({}) VALUES ({}) RETURNING {}",
        quote_ident(&table_name(&doctype.name)),
        column_list(doctype),
        values.join(", "),
        column_list(doctype)
    )
}

/// Placeholders `$1..$n` for the changes (in key order), `$n+1` actor, `$n+2` name.
/// `changes` has passed validation, so every key is a field of the DocType (the `text` fallback
/// cast is unreachable; an unknown column would be rejected by the database, never interpolated).
fn update_sql(doctype: &DocType, changes: &BTreeMap<String, Value>) -> String {
    let mut sets: Vec<String> = Vec::with_capacity(changes.len() + 3);
    for (i, name) in changes.keys().enumerate() {
        let cast = doctype
            .field(name)
            .map_or("text", |f| cast_type(&f.field_type));
        sets.push(format!("{} = ${}::{cast}", quote_ident(name), i + 1));
    }
    let n = changes.len();
    sets.push("\"modified_at\" = now()".to_owned());
    sets.push(format!("\"modified_by\" = ${}::text", n + 1));
    sets.push("\"version\" = \"version\" + 1".to_owned());
    format!(
        "UPDATE {} SET {} WHERE \"name\" = ${}::text RETURNING {}",
        quote_ident(&table_name(&doctype.name)),
        sets.join(", "),
        n + 2,
        column_list(doctype)
    )
}

fn decode_row(doctype: &DocType, row: &Row) -> Result<StoredDocument, DbError> {
    let mut values = BTreeMap::new();
    for (i, field) in doctype.fields.iter().enumerate() {
        let value = decode(row, STANDARD_COLUMNS.len() + i, &field.field_type)
            .map_err(|e| DbError::decode(&doctype.name, &field.name, &e))?;
        values.insert(field.name.clone(), value);
    }
    Ok(StoredDocument {
        id: row.try_get(0)?,
        name: row.try_get(1)?,
        owner: row.try_get(2)?,
        created_at: row.try_get(3)?,
        modified_at: row.try_get(4)?,
        modified_by: row.try_get(5)?,
        version: row.try_get(6)?,
        values,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn customer() -> DocType {
        DocType::from_toml_str(
            "name = \"customer\"\nlabel = \"C\"\nnaming = { field = \"email\" }\n\
             [[fields]]\nname = \"email\"\ntype = \"data\"\nrequired = true\nunique = true\n\
             [[fields]]\nname = \"points\"\ntype = \"int\"\n",
        )
        .expect("valid DocType")
    }

    #[test]
    fn insert_sql_binds_every_value_with_a_cast() {
        assert_eq!(
            insert_sql(&customer()),
            "INSERT INTO \"doc_customer\" (\"id\", \"name\", \"owner\", \"created_at\", \"modified_at\", \
             \"modified_by\", \"version\", \"email\", \"points\") VALUES ($1::uuid, $2::text, $3::text, now(), \
             now(), $3::text, 1, $4::varchar, $5::bigint) RETURNING \"id\", \"name\", \"owner\", \"created_at\", \
             \"modified_at\", \"modified_by\", \"version\", \"email\", \"points\""
        );
    }

    #[test]
    fn update_sql_numbers_placeholders_in_key_order() {
        let changes = BTreeMap::from([
            ("points".to_owned(), Value::Int(1)),
            ("email".to_owned(), Value::Null),
        ]);
        let sql = update_sql(&customer(), &changes);
        assert!(sql.starts_with(
            "UPDATE \"doc_customer\" SET \"email\" = $1::varchar, \"points\" = $2::bigint, \
             \"modified_at\" = now(), \"modified_by\" = $3::text, \"version\" = \"version\" + 1 \
             WHERE \"name\" = $4::text RETURNING "
        ));
    }

    #[test]
    fn actor_rules() {
        assert!(check_actor("cli").is_ok());
        assert!(matches!(check_actor(""), Err(DbError::InvalidActor)));
        assert!(matches!(check_actor("a\0b"), Err(DbError::InvalidActor)));
    }
}
