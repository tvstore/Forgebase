//! Document persistence: insert, get, update and delete of one document, with its child table
//! rows, in the tables of its DocType.
//!
//! Every function takes a mutable [`GenericClient`] (a pooled connection or a caller-owned
//! [`Transaction`](tokio_postgres::Transaction)) and the [`Registry`], and runs all of its
//! statements inside `client.transaction()`: a real transaction on a pooled connection, a
//! savepoint when the caller already has a transaction. A document and its rows are therefore
//! written atomically whichever client is passed, and a failed call leaves a caller's transaction
//! usable. SQL is built only from validated, quoted identifiers and numeric placeholders with
//! explicit casts; values are always bound parameters.
//!
//! Link fields hold the target's `id` in the database; this module resolves the target `name` to
//! the `id` on the way in and back to the `name` on the way out (see [`insert`]). Table fields
//! are rows of a child DocType's table, see [`insert`] and [`update`].
//!
//! The app's lifecycle hooks ([`forgebase_core::hooks::DocTypeHooks`], registered in the
//! [`Registry`]) run inside the same transaction at fixed points: the order of every operation
//! is listed in the documentation of [`insert`], [`update`] and [`delete`]. A hook error rolls
//! everything back ([`DbError::Hook`]). Hooks cannot reach the database.

use std::collections::{BTreeMap, BTreeSet};

use forgebase_core::document::{Changes, Document, Row, ValidationError, validate};
use forgebase_core::hooks::{DocTypeHooks, HookContext, HookError, Operation};
use forgebase_core::ident::table_name;
use forgebase_core::meta::{DocType, FieldType, Naming, Registry};
use forgebase_core::value::Value;
use time::OffsetDateTime;
use tokio_postgres::GenericClient;
use tokio_postgres::Row as PgRow;
use tokio_postgres::types::ToSql;
use uuid::Uuid;

use crate::error::DbError;
use crate::ident::quote_ident;
use crate::value::{SqlParam, SqlValue, cast_type, decode};

/// The standard columns, in the order they are selected (see `plan.rs`: the DDL has the same).
const STANDARD_COLUMNS: [&str; 7] = [
    "id",
    "name",
    "owner",
    "created_at",
    "modified_at",
    "modified_by",
    "version",
];

/// How often [`get`] re-reads a document whose rows changed while it was being read.
const READ_ATTEMPTS: usize = 5;

/// A document as stored: the standard columns, the field values and the table rows.
#[derive(Debug, Clone, PartialEq)]
pub struct StoredDocument {
    /// Surrogate key (UUID v7, generated by the application).
    pub id: Uuid,
    /// The human-facing unique name.
    pub name: String,
    /// The actor that created the document.
    pub owner: String,
    /// Creation time (database `now()`, that is the transaction start time).
    pub created_at: OffsetDateTime,
    /// Time of the last change (database `now()`).
    pub modified_at: OffsetDateTime,
    /// The actor that made the last change.
    pub modified_by: String,
    /// Starts at 1 and is incremented by every update.
    pub version: i64,
    /// One entry per column field of the DocType (every field except Table fields), in
    /// field-name order; [`Value::Null`] when absent. A Link field holds the target document's
    /// `name` as [`Value::Text`].
    pub values: BTreeMap<String, Value>,
    /// One entry per Table field of the DocType (an empty list when there are no rows): the rows
    /// in order, each with one entry per field of the child DocType. Row ids and positions are
    /// not exposed: the position is the place in the list, and the ids change when a table's rows
    /// are replaced (see [`update`]).
    pub tables: BTreeMap<String, Vec<Row>>,
}

/// Inserts a document and returns it as stored.
///
/// `doctype` is the name of a DocType in `registry`; it must not be a child DocType
/// ([`DbError::ChildDocType`]), and a name the registry does not know is
/// [`DbError::UnknownDocType`]. `doc` is validated first
/// ([`forgebase_core::document::validate`], all problems collected in [`DbError::Validation`]).
/// The name follows the DocType's naming rule: with [`Naming::Random`] it is the new UUID v7 and
/// `doc.name` must be `None`; with [`Naming::Field`] it is the value of that field and
/// `doc.name` must be `None` or equal to it ([`DbError::Naming`]). `actor` (a non-empty string
/// without NUL, [`DbError::InvalidActor`]) is recorded as `owner` and `modified_by`; it is not
/// authenticated here. `created_at` and `modified_at` come from the database's `now()`, and
/// `version` is 1. A duplicate value in a `unique` field or a duplicate name is
/// [`DbError::UniqueViolation`].
///
/// **Atomicity.** Everything runs in `client.transaction()` (see the module documentation): the
/// document and all its rows are written, or nothing is. That holds on a pooled connection too.
///
/// **Pipeline.** In this order: the DocType must not be a child DocType; the registered
/// `before_insert` hooks run on `doc` (in registration order, and they may modify it); the
/// `validate` hooks run; the framework validates the result ([`forgebase_core::document::validate`]);
/// Links are resolved; the name is chosen; the document and its rows are written. The hooks see
/// the document **before** framework validation, so it may be invalid, but the validation runs
/// again after them. A hook error is [`DbError::Hook`] and nothing is written.
///
/// **Links.** A non-null Link value, in the document or in a row, is the `name` of a document of
/// the target DocType. Each one is looked up with `SELECT "id" ... FOR KEY SHARE` on the same
/// transaction, which locks the target against a concurrent delete until the transaction ends
/// (so the lock covers the write). A name that does not exist is a
/// [`ValidationError::LinkNotFound`] in [`DbError::Validation`] (wrapped in
/// [`ValidationError::InRow`] for a row), together with the other problems.
///
/// **Table rows.** `doc.tables` holds the rows of each Table field. They are inserted after the
/// document, one `INSERT` per row, with new UUID v7 ids, the document's id as `parent_id` and
/// `idx` 1, 2, 3, ... in list order.
pub async fn insert(
    client: &mut impl GenericClient,
    registry: &Registry,
    doctype: &str,
    doc: Document,
    actor: &str,
) -> Result<StoredDocument, DbError> {
    let doctype = document_doctype(registry, doctype)?;
    let tx = client.transaction().await?;
    let stored = insert_in(&tx, registry, doctype, doc, actor).await?;
    tx.commit().await?;
    Ok(stored)
}

async fn insert_in(
    client: &impl GenericClient,
    registry: &Registry,
    doctype: &DocType,
    mut doc: Document,
    actor: &str,
) -> Result<StoredDocument, DbError> {
    check_actor(actor)?;
    let ctx = HookContext {
        doctype: &doctype.name,
        actor,
        operation: Operation::Insert,
    };
    run_hooks(registry, doctype, "before_insert", |hooks| {
        hooks.before_insert(&ctx, &mut doc)
    })?;
    run_hooks(registry, doctype, "validate", |hooks| {
        hooks.validate(&ctx, &mut doc)
    })?;
    let mut errors = validate(registry, doctype, &doc).err().unwrap_or_default();
    let (links, writes) = resolve(
        client,
        registry,
        doctype,
        &doc.values,
        &doc.tables,
        &mut errors,
    )
    .await?;
    if !errors.is_empty() {
        return Err(DbError::Validation(errors));
    }
    let id = Uuid::now_v7();
    let name = new_name(doctype, &doc, id)?;

    let sql = insert_sql(doctype);
    let (id_value, name_value, actor_value) = (id, name, actor);
    let mut params: Vec<&(dyn ToSql + Sync)> = vec![&id_value, &name_value, &actor_value];
    let null = Value::Null;
    let bound: Vec<SqlParam<'_>> = doctype
        .column_fields()
        .map(|field| {
            sql_param(
                &field.field_type,
                &links,
                &field.name,
                doc.values.get(&field.name).unwrap_or(&null),
            )
        })
        .collect();
    params.extend(bound.iter().map(|v| v as &(dyn ToSql + Sync)));

    let row = client
        .query_one(&sql, &params)
        .await
        .map_err(|e| DbError::from_write(e, doctype))?;
    let mut stored = decode_row(doctype, &row)?;
    write_rows(client, stored.id, &writes).await?;
    stored.tables = load_tables(client, registry, doctype, stored.id).await?;
    Ok(stored)
}

/// Returns the document with this name, or `None`. Link values are the target documents' names;
/// `tables` holds the rows of every Table field in order.
///
/// A document with Table fields is read with several statements. If an update commits in
/// between, the read starts over (a document and its rows are never mixed from two versions,
/// also at READ COMMITTED); after a few unlucky attempts it fails with
/// [`DbError::ChangedWhileReading`].
pub async fn get(
    client: &mut impl GenericClient,
    registry: &Registry,
    doctype: &str,
    name: &str,
) -> Result<Option<StoredDocument>, DbError> {
    let doctype = document_doctype(registry, doctype)?;
    // Without Table fields the read is one statement, already consistent: no transaction needed.
    if doctype.table_fields().next().is_none() {
        return get_in(&*client, registry, doctype, name).await;
    }
    let tx = client.transaction().await?;
    let stored = get_in(&tx, registry, doctype, name).await?;
    tx.commit().await?;
    Ok(stored)
}

async fn get_in(
    client: &impl GenericClient,
    registry: &Registry,
    doctype: &DocType,
    name: &str,
) -> Result<Option<StoredDocument>, DbError> {
    for _ in 0..READ_ATTEMPTS {
        let Some(row) = client.query_opt(&get_sql(doctype), &[&name]).await? else {
            return Ok(None);
        };
        let mut stored = decode_row(doctype, &row)?;
        if doctype.table_fields().next().is_none() {
            return Ok(Some(stored));
        }
        stored.tables = load_tables(client, registry, doctype, stored.id).await?;
        // An update changes the version together with the rows, atomically: if the version is
        // still the one read first, the rows belong to it.
        let sql = format!(
            "SELECT \"version\" FROM {} WHERE \"id\" = $1::uuid",
            quote_ident(&table_name(&doctype.name))
        );
        let current: Option<i64> = client
            .query_opt(&sql, &[&stored.id])
            .await?
            .map(|row| row.try_get(0))
            .transpose()?;
        if current == Some(stored.version) {
            return Ok(Some(stored));
        }
    }
    Err(DbError::ChangedWhileReading {
        doctype: doctype.name.clone(),
        name: name.to_owned(),
    })
}

/// Changes the given fields of an existing document and returns it as stored.
///
/// Only the fields in `changes.values` change (a [`Value::Null`] clears one); a Table field in
/// `changes.tables` replaces its rows when they differ from the stored ones (an empty list removes
/// every row; identical rows are left alone and keep their ids), and a Table field that is not
/// mentioned keeps its rows. Changing the naming field is rejected
/// ([`DbError::Naming`]): renames are not supported yet. Empty `changes` are
/// [`DbError::NoChanges`]; changes to tables only are fine. `modified_at` is set to the
/// database's `now()`, `modified_by` to `actor`, and `version` is incremented; `created_at` and
/// `owner` stay.
///
/// **Pipeline.** The hooks and the validation see the **whole** document, not only the changes.
/// In this order:
///
/// 1. the stored document and its rows are read with a row lock (`FOR NO KEY UPDATE`): an
///    unknown name is [`DbError::NotFound`] and a `version` other than `expected_version` is
///    [`DbError::Conflict`], both before any hook runs;
/// 2. the changes are merged into it: the stored values overlaid with `changes.values`, and the
///    rows of a Table field from `changes.tables` when given, else the stored rows;
/// 3. a change to the naming field is rejected;
/// 4. the registered `validate` hooks run on the merged document (in registration order, and
///    they may modify it; the naming field must stay as it is);
/// 5. the framework validates the whole merged document
///    ([`forgebase_core::document::validate`]), so a stored value that is not valid any more (a
///    required field that is null in the row, for example) is reported too, and a hook cannot
///    leave an invalid document;
/// 6. Links are resolved, then **every column field** of the merged document is written, and
///    the rows of every Table field whose rows differ from the stored ones (given in `changes` or
///    modified by a hook) are replaced, so row ids change only for a table whose rows changed. `version`
///    is incremented in the same statement as the document row, which comes first.
///
/// An update is an explicit save: it increments `version` and sets `modified_at` even when the
/// merged document equals the stored one (for example when the changes repeat the stored values
/// and the hooks change nothing). Every change to child rows bumps the version.
///
/// A hook error is [`DbError::Hook`] and nothing is written. The DocType rules, the transaction
/// and the Link handling are those of [`insert`].
///
/// **Optimistic concurrency.** The update is applied only if the document's current `version`
/// equals `expected_version` (the version the caller read). Of two concurrent updates with the
/// same `expected_version`, exactly one succeeds. Conflict detection assumes READ COMMITTED, the
/// PostgreSQL default: the second writer waits for the row lock and then re-checks the
/// version. In a caller-owned transaction at REPEATABLE READ or SERIALIZABLE the losing writer
/// instead gets a serialization failure (SQLSTATE 40001, [`DbError::Postgres`], not
/// `Conflict`); retry the whole transaction.
pub async fn update(
    client: &mut impl GenericClient,
    registry: &Registry,
    doctype: &str,
    name: &str,
    expected_version: i64,
    changes: &Changes,
    actor: &str,
) -> Result<StoredDocument, DbError> {
    let doctype = document_doctype(registry, doctype)?;
    let tx = client.transaction().await?;
    let stored = update_in(
        &tx,
        registry,
        doctype,
        name,
        expected_version,
        changes,
        actor,
    )
    .await?;
    tx.commit().await?;
    Ok(stored)
}

async fn update_in(
    client: &impl GenericClient,
    registry: &Registry,
    doctype: &DocType,
    name: &str,
    expected_version: i64,
    changes: &Changes,
    actor: &str,
) -> Result<StoredDocument, DbError> {
    check_actor(actor)?;
    if changes.is_empty() {
        return Err(DbError::NoChanges);
    }
    // `FOR NO KEY UPDATE` is the lock the UPDATE itself takes: it serializes with other updates
    // and deletes but leaves Link lookups (`FOR KEY SHARE`) and foreign key checks unblocked.
    // PostgreSQL upgrades it to `FOR UPDATE` when a unique (key) column changes.
    let current = lock_current(
        client,
        registry,
        doctype,
        name,
        expected_version,
        "FOR NO KEY UPDATE",
    )
    .await?;
    let mut doc = as_document(&current);
    doc.values.extend(changes.values.clone());
    doc.tables.extend(changes.tables.clone());

    if let Naming::Field(field) = &doctype.naming
        && changes.values.contains_key(field)
    {
        return Err(DbError::Naming(format!(
            "field `{field}` gives the document its name and cannot be changed (renames are not supported yet)"
        )));
    }
    let ctx = HookContext {
        doctype: &doctype.name,
        actor,
        operation: Operation::Update,
    };
    run_hooks(registry, doctype, "validate", |hooks| {
        hooks.validate(&ctx, &mut doc)
    })?;
    if let Naming::Field(field) = &doctype.naming
        && doc.values.get(field) != Some(&Value::Text(current.name.clone()))
    {
        return Err(DbError::Naming(format!(
            "field `{field}` gives the document its name and cannot be changed, also not by a hook (renames are not supported yet)"
        )));
    }
    let mut errors = validate(registry, doctype, &doc).err().unwrap_or_default();

    // Every column field is written (a value a hook removed is cleared); of the tables only
    // those whose rows differ from the stored ones.
    let null = Value::Null;
    let columns: BTreeMap<String, Value> = doctype
        .column_fields()
        .map(|field| {
            (
                field.name.clone(),
                doc.values.get(&field.name).unwrap_or(&null).clone(),
            )
        })
        .collect();
    let changed_tables: BTreeMap<String, Vec<Row>> = doc
        .tables
        .iter()
        .filter(|(field, rows)| current.tables.get(*field) != Some(*rows))
        .map(|(field, rows)| (field.clone(), rows.clone()))
        .collect();
    let (links, writes) = resolve(
        client,
        registry,
        doctype,
        &columns,
        &changed_tables,
        &mut errors,
    )
    .await?;
    if !errors.is_empty() {
        return Err(DbError::Validation(errors));
    }

    let sql = update_sql(doctype, &columns);
    let bound: Vec<SqlParam<'_>> = columns
        .iter()
        .map(|(field, value)| {
            // `columns` holds column fields only, so every key is a field; the fallback is never used.
            let field_type = doctype.field(field).map(|f| &f.field_type);
            field_type.map_or(SqlParam::Value(SqlValue(value)), |t| {
                sql_param(t, &links, field, value)
            })
        })
        .collect();
    let mut params: Vec<&(dyn ToSql + Sync)> =
        bound.iter().map(|v| v as &(dyn ToSql + Sync)).collect();
    params.push(&actor);
    params.push(&name);
    params.push(&expected_version);

    let row = client
        .query_opt(&sql, &params)
        .await
        .map_err(|e| DbError::from_write(e, doctype))?;
    // The row is locked and its version was checked, so it matches; this is only a safeguard.
    let Some(row) = row else {
        return Err(stale_or_missing(client, doctype, name, expected_version).await?);
    };
    let mut stored = decode_row(doctype, &row)?;
    for write in &writes {
        let sql = format!(
            "DELETE FROM {} WHERE \"parent_id\" = $1::uuid",
            quote_ident(&table_name(&write.child.name))
        );
        client.execute(&sql, &[&stored.id]).await?;
    }
    write_rows(client, stored.id, &writes).await?;
    stored.tables = load_tables(client, registry, doctype, stored.id).await?;
    Ok(stored)
}

/// Deletes the document with this name, and its table rows, if its current `version` equals
/// `expected_version`. The `actor` is passed to the hooks (not stored, as there is no audit yet,
/// and not authenticated); an empty
/// one is [`DbError::InvalidActor`], as for [`insert`] and [`update`].
///
/// A different version is [`DbError::Conflict`] (nothing is deleted; under REPEATABLE READ or
/// SERIALIZABLE a stale writer gets SQLSTATE 40001 as [`DbError::Postgres`] instead, see
/// [`update`]); an unknown name is [`DbError::NotFound`]. The rows go with the document (the
/// `parent_id` foreign key is `ON DELETE CASCADE`). A document that other documents still link
/// to cannot be deleted: [`DbError::LinkedDocumentExists`] names the linking DocType (the
/// links are `ON DELETE RESTRICT`; for a link in a table row, the DocType that owns the row). A
/// failed delete leaves a caller-owned transaction usable (the call ran in a savepoint).
///
/// **Pipeline.** In this order: the stored document and its rows are read with a row lock
/// (`FOR UPDATE`; an unknown name or another version is reported here, before any hook runs);
/// the registered `before_delete` hooks run with the stored document, rows included (a hook error
/// is [`DbError::Hook`] and nothing is deleted); the document is deleted.
pub async fn delete(
    client: &mut impl GenericClient,
    registry: &Registry,
    doctype: &str,
    name: &str,
    expected_version: i64,
    actor: &str,
) -> Result<(), DbError> {
    let doctype = document_doctype(registry, doctype)?;
    let tx = client.transaction().await?;
    delete_in(&tx, registry, doctype, name, expected_version, actor).await?;
    tx.commit().await?;
    Ok(())
}

async fn delete_in(
    client: &impl GenericClient,
    registry: &Registry,
    doctype: &DocType,
    name: &str,
    expected_version: i64,
    actor: &str,
) -> Result<(), DbError> {
    check_actor(actor)?;
    // `FOR UPDATE` makes concurrent linkers (`FOR KEY SHARE`) wait, so `before_delete` hooks do
    // not run for a delete that a new link would then refuse.
    let current = lock_current(
        client,
        registry,
        doctype,
        name,
        expected_version,
        "FOR UPDATE",
    )
    .await?;
    let doc = as_document(&current);
    let ctx = HookContext {
        doctype: &doctype.name,
        actor,
        operation: Operation::Delete,
    };
    run_hooks(registry, doctype, "before_delete", |hooks| {
        hooks.before_delete(&ctx, &doc)
    })?;
    let sql = format!(
        "DELETE FROM {} WHERE \"name\" = $1::text AND \"version\" = $2::bigint",
        quote_ident(&table_name(&doctype.name))
    );
    let deleted = client
        .execute(&sql, &[&name, &expected_version])
        .await
        .map_err(|e| match DbError::from_delete(e, &doctype.name, name) {
            DbError::LinkedDocumentExists {
                doctype,
                name,
                referenced_by: Some(by),
            } => DbError::LinkedDocumentExists {
                doctype,
                name,
                referenced_by: Some(owning_doctype(registry, by)),
            },
            other => other,
        })?;
    if deleted == 0 {
        return Err(stale_or_missing(client, doctype, name, expected_version).await?);
    }
    Ok(())
}

/// Calls `call` for every hook set registered for the DocType, in registration order, and stops
/// at the first error, which becomes [`DbError::Hook`] naming `hook`.
fn run_hooks(
    registry: &Registry,
    doctype: &DocType,
    hook: &'static str,
    mut call: impl FnMut(&dyn DocTypeHooks) -> Result<(), HookError>,
) -> Result<(), DbError> {
    for hooks in registry.hooks(&doctype.name) {
        call(hooks.as_ref()).map_err(|error| DbError::Hook {
            doctype: doctype.name.clone(),
            hook,
            message: error.message().to_owned(),
        })?;
    }
    Ok(())
}

/// The stored document as the [`Document`] hooks and validation work on.
fn as_document(stored: &StoredDocument) -> Document {
    Document {
        name: Some(stored.name.clone()),
        values: stored.values.clone(),
        tables: stored.tables.clone(),
    }
}

/// Reads the document with this name and its rows, locking the document row with `lock` (a
/// fixed `FOR ...` clause) until the transaction ends. An unknown name is
/// [`DbError::NotFound`], a version other than `expected_version` is [`DbError::Conflict`];
/// nothing else has been done at that point. Writers of the rows take this lock first, so the
/// rows read here cannot change under the caller.
async fn lock_current(
    client: &impl GenericClient,
    registry: &Registry,
    doctype: &DocType,
    name: &str,
    expected_version: i64,
    lock: &'static str,
) -> Result<StoredDocument, DbError> {
    let sql = format!("{} {lock}", get_sql(doctype));
    let Some(row) = client.query_opt(&sql, &[&name]).await? else {
        return Err(DbError::NotFound {
            doctype: doctype.name.clone(),
            name: name.to_owned(),
        });
    };
    let mut stored = decode_row(doctype, &row)?;
    if stored.version != expected_version {
        return Err(DbError::Conflict {
            doctype: doctype.name.clone(),
            name: name.to_owned(),
            expected: expected_version,
            current: stored.version,
        });
    }
    stored.tables = load_tables(client, registry, doctype, stored.id).await?;
    Ok(stored)
}

/// For a link from a child table row, the DocType that owns the row; any other name unchanged.
fn owning_doctype(registry: &Registry, referencing: String) -> String {
    registry
        .get(&referencing)
        .filter(|d| d.is_child)
        .and_then(|child| registry.parent_of(&child.name))
        .map_or(referencing, |(parent, _)| parent.name.clone())
}

/// The DocType that documents of `name` belong to: it must be in the registry and not a child.
fn document_doctype<'a>(registry: &'a Registry, name: &str) -> Result<&'a DocType, DbError> {
    match registry.get(name) {
        None => Err(DbError::UnknownDocType {
            name: name.to_owned(),
        }),
        Some(doctype) if doctype.is_child => Err(DbError::ChildDocType {
            doctype: name.to_owned(),
        }),
        Some(doctype) => Ok(doctype),
    }
}

/// The child DocType of a Table field. A registry that passed `check_references` has it.
fn child_doctype<'a>(registry: &'a Registry, target: &str) -> Result<&'a DocType, DbError> {
    registry.get(target).ok_or_else(|| DbError::UnknownDocType {
        name: target.to_owned(),
    })
}

/// Why a write that matched no row (`name` and `version`) did nothing: the document does not
/// exist ([`DbError::NotFound`]) or has another version ([`DbError::Conflict`]).
async fn stale_or_missing(
    client: &impl GenericClient,
    doctype: &DocType,
    name: &str,
    expected_version: i64,
) -> Result<DbError, DbError> {
    let sql = format!(
        "SELECT \"version\" FROM {} WHERE \"name\" = $1::text",
        quote_ident(&table_name(&doctype.name))
    );
    Ok(match client.query_opt(&sql, &[&name]).await? {
        None => DbError::NotFound {
            doctype: doctype.name.clone(),
            name: name.to_owned(),
        },
        Some(row) => DbError::Conflict {
            doctype: doctype.name.clone(),
            name: name.to_owned(),
            expected: expected_version,
            current: row.try_get(0)?,
        },
    })
}

/// The rows to write for one Table field, with their Link values already resolved.
struct TableWrite<'a> {
    child: &'a DocType,
    rows: Vec<(&'a Row, BTreeMap<String, Uuid>)>,
}

/// Resolves the Links of the document's values and of every row. Returns the ids of the
/// document's Links and the rows to write; a Link name that does not exist is added to `errors`.
async fn resolve<'a>(
    client: &impl GenericClient,
    registry: &'a Registry,
    doctype: &DocType,
    values: &BTreeMap<String, Value>,
    tables: &'a BTreeMap<String, Vec<Row>>,
    errors: &mut Vec<ValidationError>,
) -> Result<(BTreeMap<String, Uuid>, Vec<TableWrite<'a>>), DbError> {
    // Fields that already have a problem are not looked up (their value may not even be
    // sendable to the database, for example text with NUL).
    let skip: BTreeSet<String> = errors
        .iter()
        .filter(|e| !matches!(e, ValidationError::InRow { .. }))
        .map(|e| e.field().to_owned())
        .collect();
    let (links, found) = resolve_links(client, doctype, values, &skip).await?;
    errors.extend(found);

    let mut writes = Vec::new();
    for (name, rows) in tables {
        let Some(FieldType::Table { target }) = doctype.field(name).map(|f| &f.field_type) else {
            continue; // reported by validation
        };
        let child = child_doctype(registry, target)?;
        let mut resolved = Vec::with_capacity(rows.len());
        for (i, row) in rows.iter().enumerate() {
            let position = i + 1;
            let skip: BTreeSet<String> = errors
                .iter()
                .filter_map(|e| match e {
                    ValidationError::InRow { field, row, error }
                        if field == name && *row == position =>
                    {
                        Some(error.field().to_owned())
                    }
                    _ => None,
                })
                .collect();
            let (ids, found) = resolve_links(client, child, row, &skip).await?;
            errors.extend(found.into_iter().map(|error| ValidationError::InRow {
                field: name.clone(),
                row: position,
                error: Box::new(error),
            }));
            resolved.push((row, ids));
        }
        writes.push(TableWrite {
            child,
            rows: resolved,
        });
    }
    Ok((links, writes))
}

/// Resolves the Link values in `values` (name -> target `id`), locking each target row against
/// deletion. A name that does not exist is returned as [`ValidationError::LinkNotFound`].
/// Fields in `skip` are not looked up.
async fn resolve_links(
    client: &impl GenericClient,
    doctype: &DocType,
    values: &BTreeMap<String, Value>,
    skip: &BTreeSet<String>,
) -> Result<(BTreeMap<String, Uuid>, Vec<ValidationError>), DbError> {
    let mut ids = BTreeMap::new();
    let mut errors = Vec::new();
    for (field, value) in values {
        let (Some(FieldType::Link { target }), Value::Text(target_name)) =
            (doctype.field(field).map(|f| &f.field_type), value)
        else {
            continue;
        };
        if skip.contains(field) {
            continue;
        }
        let sql = format!(
            "SELECT \"id\" FROM {} WHERE \"name\" = $1::text FOR KEY SHARE",
            quote_ident(&table_name(target))
        );
        match client.query_opt(&sql, &[target_name]).await? {
            Some(row) => {
                ids.insert(field.clone(), row.try_get::<_, Uuid>(0)?);
            }
            None => errors.push(ValidationError::LinkNotFound {
                field: field.clone(),
                target: target.clone(),
                name: target_name.clone(),
            }),
        }
    }
    Ok((ids, errors))
}

/// Inserts the rows of every table, one `INSERT` per row, numbering them from 1.
async fn write_rows(
    client: &impl GenericClient,
    parent_id: Uuid,
    writes: &[TableWrite<'_>],
) -> Result<(), DbError> {
    let null = Value::Null;
    for write in writes {
        let sql = child_insert_sql(write.child);
        for ((row, links), idx) in write.rows.iter().zip(1_i32..) {
            let id = Uuid::now_v7();
            let mut params: Vec<&(dyn ToSql + Sync)> = vec![&id, &parent_id, &idx];
            let bound: Vec<SqlParam<'_>> = write
                .child
                .column_fields()
                .map(|field| {
                    sql_param(
                        &field.field_type,
                        links,
                        &field.name,
                        row.get(&field.name).unwrap_or(&null),
                    )
                })
                .collect();
            params.extend(bound.iter().map(|v| v as &(dyn ToSql + Sync)));
            client.execute(&sql, &params).await?;
        }
    }
    Ok(())
}

/// Reads the rows of every Table field of a document, in order.
async fn load_tables(
    client: &impl GenericClient,
    registry: &Registry,
    doctype: &DocType,
    parent_id: Uuid,
) -> Result<BTreeMap<String, Vec<Row>>, DbError> {
    let mut tables = BTreeMap::new();
    for (field, target) in doctype.table_fields() {
        let child = child_doctype(registry, target)?;
        let rows = client
            .query(&child_select_sql(child), &[&parent_id])
            .await?
            .iter()
            .map(|row| decode_fields(child, row, 0))
            .collect::<Result<Vec<_>, _>>()?;
        tables.insert(field.name.clone(), rows);
    }
    Ok(tables)
}

/// The bound parameter for one field: the resolved `id` for a Link, else the value itself.
fn sql_param<'a>(
    field_type: &FieldType,
    links: &BTreeMap<String, Uuid>,
    field: &str,
    value: &'a Value,
) -> SqlParam<'a> {
    match field_type {
        FieldType::Link { .. } => SqlParam::Link(links.get(field).copied()),
        _ => SqlParam::Value(SqlValue(value)),
    }
}

fn check_actor(actor: &str) -> Result<(), DbError> {
    if actor.is_empty() || actor.contains('\0') {
        return Err(DbError::InvalidActor);
    }
    Ok(())
}

/// The name for a new document. `doc` has passed validation.
fn new_name(doctype: &DocType, doc: &Document, id: Uuid) -> Result<String, DbError> {
    match &doctype.naming {
        Naming::Random => {
            if doc.name.is_some() {
                return Err(DbError::Naming(format!(
                    "DocType `{}` uses random naming: the name is generated and cannot be given",
                    doctype.name
                )));
            }
            Ok(id.hyphenated().to_string())
        }
        Naming::Field(field) => {
            let Some(Value::Text(name)) = doc.values.get(field) else {
                return Err(DbError::Naming(format!(
                    "field `{field}` must hold the document name"
                )));
            };
            if doc.name.as_ref().is_some_and(|given| given != name) {
                return Err(DbError::Naming(format!(
                    "the given name differs from the value of naming field `{field}`"
                )));
            }
            Ok(name.clone())
        }
    }
}

/// `"id", "name", ..., "<field>", ...`: the columns of the table, in decode order.
fn column_list(doctype: &DocType) -> String {
    STANDARD_COLUMNS
        .iter()
        .copied()
        .chain(doctype.column_fields().map(|f| f.name.as_str()))
        .map(quote_ident)
        .collect::<Vec<_>>()
        .join(", ")
}

/// What every statement returns for the fields, in decode order: the column, except that a Link
/// column is replaced by the target document's `name` (a scalar subquery on the target's `id`,
/// aliased to the field name; the outer column is qualified with the table name so a self-link
/// resolves).
fn field_items(doctype: &DocType) -> Vec<String> {
    let table = quote_ident(&table_name(&doctype.name));
    doctype
        .column_fields()
        .map(|field| {
            let column = quote_ident(&field.name);
            match &field.field_type {
                FieldType::Link { target } => format!(
                    "(SELECT t.\"name\" FROM {} t WHERE t.\"id\" = {table}.{column}) AS {column}",
                    quote_ident(&table_name(target))
                ),
                _ => column,
            }
        })
        .collect()
}

/// What every statement on a document table returns, in decode order: the standard columns, then
/// [`field_items`].
fn select_list(doctype: &DocType) -> String {
    let mut items: Vec<String> = STANDARD_COLUMNS.iter().copied().map(quote_ident).collect();
    items.extend(field_items(doctype));
    items.join(", ")
}

fn get_sql(doctype: &DocType) -> String {
    format!(
        "SELECT {} FROM {} WHERE \"name\" = $1::text",
        select_list(doctype),
        quote_ident(&table_name(&doctype.name))
    )
}

/// `$1::<type>, $2::<type>, ...` for the column fields, numbered from `first`.
fn field_placeholders(doctype: &DocType, first: usize) -> Vec<String> {
    doctype
        .column_fields()
        .enumerate()
        .map(|(i, field)| format!("${}::{}", first + i, cast_type(&field.field_type)))
        .collect()
}

/// Placeholders `$1` (id), `$2` (name) and `$3` (actor, used twice), then one per column field.
fn insert_sql(doctype: &DocType) -> String {
    let mut values = vec![
        "$1::uuid".to_owned(),
        "$2::text".to_owned(),
        "$3::text".to_owned(),
        "now()".to_owned(),
        "now()".to_owned(),
        "$3::text".to_owned(),
        "1".to_owned(),
    ];
    values.extend(field_placeholders(doctype, 4));
    format!(
        "INSERT INTO {} ({}) VALUES ({}) RETURNING {}",
        quote_ident(&table_name(&doctype.name)),
        column_list(doctype),
        values.join(", "),
        select_list(doctype)
    )
}

/// Placeholders `$1` (row id), `$2` (parent id) and `$3` (idx), then one per field of the child.
fn child_insert_sql(child: &DocType) -> String {
    let columns: Vec<String> = ["id", "parent_id", "idx"]
        .into_iter()
        .chain(child.column_fields().map(|f| f.name.as_str()))
        .map(quote_ident)
        .collect();
    let mut values = vec![
        "$1::uuid".to_owned(),
        "$2::uuid".to_owned(),
        "$3::integer".to_owned(),
    ];
    values.extend(field_placeholders(child, 4));
    format!(
        "INSERT INTO {} ({}) VALUES ({})",
        quote_ident(&table_name(&child.name)),
        columns.join(", "),
        values.join(", ")
    )
}

/// The rows of a parent (`$1` = its id) in order, as [`field_items`].
fn child_select_sql(child: &DocType) -> String {
    format!(
        "SELECT {} FROM {} WHERE \"parent_id\" = $1::uuid ORDER BY \"idx\"",
        field_items(child).join(", "),
        quote_ident(&table_name(&child.name))
    )
}

/// Placeholders `$1..$n` for the changes (in key order), `$n+1` actor, `$n+2` name,
/// `$n+3` expected version.
/// `changes` has passed validation, so every key is a field of the DocType (the `text` fallback
/// cast is unreachable; an unknown column would be rejected by the database, never interpolated).
fn update_sql(doctype: &DocType, changes: &BTreeMap<String, Value>) -> String {
    let mut sets: Vec<String> = Vec::with_capacity(changes.len() + 3);
    for (i, name) in changes.keys().enumerate() {
        let cast = doctype
            .field(name)
            .map_or("text", |f| cast_type(&f.field_type));
        sets.push(format!("{} = ${}::{cast}", quote_ident(name), i + 1));
    }
    let n = changes.len();
    sets.push("\"modified_at\" = now()".to_owned());
    sets.push(format!("\"modified_by\" = ${}::text", n + 1));
    sets.push("\"version\" = \"version\" + 1".to_owned());
    format!(
        "UPDATE {} SET {} WHERE \"name\" = ${}::text AND \"version\" = ${}::bigint RETURNING {}",
        quote_ident(&table_name(&doctype.name)),
        sets.join(", "),
        n + 2,
        n + 3,
        select_list(doctype)
    )
}

/// Decodes the column fields of `doctype` from `row`, starting at column `offset`.
fn decode_fields(
    doctype: &DocType,
    row: &PgRow,
    offset: usize,
) -> Result<BTreeMap<String, Value>, DbError> {
    let mut values = BTreeMap::new();
    for (i, field) in doctype.column_fields().enumerate() {
        let value = decode(row, offset + i, &field.field_type)
            .map_err(|e| DbError::decode(&doctype.name, &field.name, &e))?;
        values.insert(field.name.clone(), value);
    }
    Ok(values)
}

/// Decodes a row of [`select_list`]. `tables` is left empty for the caller to fill.
fn decode_row(doctype: &DocType, row: &PgRow) -> Result<StoredDocument, DbError> {
    Ok(StoredDocument {
        id: row.try_get(0)?,
        name: row.try_get(1)?,
        owner: row.try_get(2)?,
        created_at: row.try_get(3)?,
        modified_at: row.try_get(4)?,
        modified_by: row.try_get(5)?,
        version: row.try_get(6)?,
        values: decode_fields(doctype, row, STANDARD_COLUMNS.len())?,
        tables: BTreeMap::new(),
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn customer() -> DocType {
        DocType::from_toml_str(
            "name = \"customer\"\nlabel = \"C\"\nnaming = { field = \"email\" }\n\
             [[fields]]\nname = \"email\"\ntype = \"data\"\nrequired = true\nunique = true\n\
             [[fields]]\nname = \"points\"\ntype = \"int\"\n",
        )
        .expect("valid DocType")
    }

    #[test]
    fn insert_sql_binds_every_value_with_a_cast() {
        assert_eq!(
            insert_sql(&customer()),
            "INSERT INTO \"doc_customer\" (\"id\", \"name\", \"owner\", \"created_at\", \"modified_at\", \
             \"modified_by\", \"version\", \"email\", \"points\") VALUES ($1::uuid, $2::text, $3::text, now(), \
             now(), $3::text, 1, $4::varchar, $5::bigint) RETURNING \"id\", \"name\", \"owner\", \"created_at\", \
             \"modified_at\", \"modified_by\", \"version\", \"email\", \"points\""
        );
    }

    #[test]
    fn update_sql_numbers_placeholders_in_key_order() {
        let changes = BTreeMap::from([
            ("points".to_owned(), Value::Int(1)),
            ("email".to_owned(), Value::Null),
        ]);
        let sql = update_sql(&customer(), &changes);
        assert!(sql.starts_with(
            "UPDATE \"doc_customer\" SET \"email\" = $1::varchar, \"points\" = $2::bigint, \
             \"modified_at\" = now(), \"modified_by\" = $3::text, \"version\" = \"version\" + 1 \
             WHERE \"name\" = $4::text AND \"version\" = $5::bigint RETURNING "
        ));
    }

    fn order() -> DocType {
        DocType::from_toml_str(
            "name = \"order\"\nlabel = \"O\"\n\
             [[fields]]\nname = \"customer\"\ntype = \"link\"\ntarget = \"customer\"\n\
             [[fields]]\nname = \"parent\"\ntype = \"link\"\ntarget = \"order\"\n",
        )
        .expect("valid DocType")
    }

    #[test]
    fn links_are_written_as_uuid_and_read_back_as_names() {
        let sql = insert_sql(&order());
        assert!(
            sql.contains("$4::uuid, $5::uuid) RETURNING"),
            "bound as ids: {sql}"
        );
        // The INSERT column list is plain; only RETURNING resolves names.
        assert!(
            sql.contains("\"version\", \"customer\", \"parent\") VALUES"),
            "{sql}"
        );
        assert!(
            sql.ends_with(
                "\"version\", (SELECT t.\"name\" FROM \"doc_customer\" t WHERE t.\"id\" = \"doc_order\".\"customer\") AS \"customer\", \
                 (SELECT t.\"name\" FROM \"doc_order\" t WHERE t.\"id\" = \"doc_order\".\"parent\") AS \"parent\""
            ),
            "{sql}"
        );
        assert!(get_sql(&order()).contains("AS \"customer\""));
    }

    fn line() -> DocType {
        DocType::from_toml_str(
            "name = \"line\"\nlabel = \"L\"\nis_child = true\n\
             [[fields]]\nname = \"qty\"\ntype = \"int\"\n\
             [[fields]]\nname = \"customer\"\ntype = \"link\"\ntarget = \"customer\"\n",
        )
        .expect("valid DocType")
    }

    fn with_table() -> DocType {
        DocType::from_toml_str(
            "name = \"ord\"\nlabel = \"O\"\n\
             [[fields]]\nname = \"title\"\ntype = \"data\"\n\
             [[fields]]\nname = \"lines\"\ntype = \"table\"\ntarget = \"line\"\n\
             [[fields]]\nname = \"note\"\ntype = \"text\"\n",
        )
        .expect("valid DocType")
    }

    #[test]
    fn a_table_field_is_not_a_column_in_any_statement() {
        let doctype = with_table();
        let insert = insert_sql(&doctype);
        assert!(
            insert.contains("(\"id\", \"name\", \"owner\", \"created_at\", \"modified_at\", \"modified_by\", \"version\", \"title\", \"note\") VALUES"),
            "{insert}"
        );
        assert!(
            insert.contains("$4::varchar, $5::text) RETURNING"),
            "{insert}"
        );
        assert!(!insert.contains("lines"), "{insert}");
        assert!(!get_sql(&doctype).contains("lines"));
        assert!(!column_list(&doctype).contains("lines"));
        assert!(!select_list(&doctype).contains("lines"));
        assert!(!field_items(&doctype).concat().contains("lines"));
        assert_eq!(field_placeholders(&doctype, 1).len(), 2);
        // No fields at all: only the meta columns change.
        let sql = update_sql(&doctype, &BTreeMap::new());
        assert!(
            sql.starts_with(
                "UPDATE \"doc_ord\" SET \"modified_at\" = now(), \"modified_by\" = $1::text, \
                 \"version\" = \"version\" + 1 WHERE \"name\" = $2::text AND \"version\" = $3::bigint RETURNING "
            ),
            "{sql}"
        );
    }

    #[test]
    fn child_statements_bind_values_and_resolve_links_on_read() {
        assert_eq!(
            child_insert_sql(&line()),
            "INSERT INTO \"doc_line\" (\"id\", \"parent_id\", \"idx\", \"qty\", \"customer\") \
             VALUES ($1::uuid, $2::uuid, $3::integer, $4::bigint, $5::uuid)"
        );
        assert_eq!(
            child_select_sql(&line()),
            "SELECT \"qty\", (SELECT t.\"name\" FROM \"doc_customer\" t WHERE t.\"id\" = \"doc_line\".\"customer\") AS \"customer\" \
             FROM \"doc_line\" WHERE \"parent_id\" = $1::uuid ORDER BY \"idx\""
        );
    }

    #[test]
    fn actor_rules() {
        assert!(check_actor("cli").is_ok());
        assert!(matches!(check_actor(""), Err(DbError::InvalidActor)));
        assert!(matches!(check_actor("a\0b"), Err(DbError::InvalidActor)));
    }
}
